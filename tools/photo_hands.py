import numpy as np
from matplotlib import font_manager
from PIL import Image, ImageDraw, ImageFont


def bands(dark):
    on, out, s = dark.any(1), [], None
    for y, v in enumerate(on):
        if v and s is None:
            s = y
        if not v and s is not None:
            out.append((s, y))
            s = None
    if s is not None:
        out.append((s, len(on)))
    return out


def gaps(strip):
    cols, out, s = strip.any(0), [], None
    for x, v in enumerate(cols):
        if not v and s is None:
            s = x
        if v and s is not None:
            out.append((s, x))
            s = None
    return [g for g in out if g[0] > 0]


LABELS = ("The photo", "Words found in it (pixel crops)", "Same words, generated by PenGPT after being conditioned on the writer's style", "New text, same style, generated by PenGPT")


def panel(path, W, drop=0, wrap=True, tint=None, font=46, pad=10, gap=14):
    im = Image.open(path).convert("RGB")
    dark = np.asarray(im).astype(int).min(2) < 235
    b = bands(dark)
    assert len(b) == 8, b
    body = lambda k: (b[k][0] - pad, b[k][1] + pad)
    y0, y1 = b[1][0] - 2, b[1][1] + 2
    photo = im.crop((0, y0, W, y1))
    if tint:
        xs = np.where(dark[b[1][0]:b[1][1]].any(0))[0]
        box = (int(xs.min()), b[1][0] - y0, min(int(xs.max()) + 1, W), b[1][1] - y0)
        paper = np.asarray(photo.crop(box)).astype(float) * np.array(tint) / 255
        photo.paste(Image.fromarray(paper.round().astype(np.uint8)), box[:2])
    rows = [photo]
    centres = lambda k: [(g[0] + g[1]) // 2 for g in gaps(dark[b[k][0]:b[k][1]]) if g[1] - g[0] >= 14 and (g[0] + g[1]) // 2 <= W - pad]
    first = centres(3)[-1 - drop]
    near = [g for g in gaps(dark[b[5][0]:b[5][1]]) if g[1] - g[0] >= 6 and first - 260 <= (g[0] + g[1]) // 2 <= min(first + 80, W - pad)]
    widest = max(near, key=lambda g: g[1] - g[0])
    cuts = {3: first, 5: (widest[0] + widest[1]) // 2 if drop else min(centres(5), key=lambda c: abs(c - first))}
    for k in (3, 5):
        y0, y1 = body(k)
        row = Image.new("RGB", (W, y1 - y0), "white")
        row.paste(im.crop((0, y0, cuts[k], y1)), (0, 0))
        rows.append(row)
    y0, y1 = body(7)
    text = dark[b[7][0]:b[7][1]]
    xs = np.where(text.any(0))[0]
    lo, hi = int(xs.min()), int(xs.max())
    if wrap:
        spaces = sorted(gaps(text[:, lo:hi + 1]), key=lambda g: g[0] - g[1])[:8]
        mid = min(spaces, key=lambda g: abs((g[0] + g[1]) / 2 - (hi - lo) / 2))
        split = lo + (mid[0] + mid[1]) // 2
        assert split - lo <= W - pad and hi - split <= W - pad, (split - lo, hi - split, W)
        h = y1 - y0
        lines = Image.new("RGB", (W, 2 * h + 10), "white")
        lines.paste(im.crop((lo, y0, split, y1)), (lo, 0))
        lines.paste(im.crop((split, y0, hi + 1, y1)), (lo, h + 10))
        rows.append(lines)
    else:
        assert hi <= W - pad, (hi, W)
        rows.append(im.crop((0, y0, W, y1)))
    italic = font_manager.findfont(font_manager.FontProperties(family="DejaVu Sans", style="italic"))
    face, slot = ImageFont.truetype(italic, font), round(1.6 * font)
    out = Image.new("RGB", (W, sum(r.height + slot + gap for r in rows)), "white")
    d, y = ImageDraw.Draw(out), 0
    for label, row in zip(LABELS, rows):
        d.text((10, y + round(0.2 * font)), label, fill=(85, 85, 85), font=face)
        out.paste(row, (0, y + slot))
        y += slot + row.height + gap
    return out


def main(out="static/photo_hands.png", gap=70):
    a = panel("static/sample_hand.png", 1650, wrap=False, font=34)
    b = panel("static/sample_print_hand.png", 1400, drop=2, tint=(227, 213, 176), font=33)
    H = min(a.height, b.height)
    a, b = (p.resize((round(p.width * H / p.height), H), Image.LANCZOS) for p in (a, b))
    both = Image.new("RGB", (a.width + gap + b.width, H), "white")
    both.paste(a, (0, 0))
    both.paste(b, (a.width + gap, 0))
    both.save(out)
    print(out, both.size, round(both.width / both.height, 2))


if __name__ == "__main__":
    main()
